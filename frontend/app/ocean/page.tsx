"use client";

import {
  ArrowDownRight,
  ArrowUpRight,
  Clock3,
  Compass,
  Droplets,
  Gauge,
  RefreshCw,
  Thermometer,
  Waves,
  Wind,
} from "lucide-react";
import Link from "next/link";
import { useEffect, useMemo, useState } from "react";

import { ObservationCharts } from "@/components/observation-charts";
import { SimulatorPanel } from "@/components/simulator-panel";
import {
  KeyValue,
  Metric,
  PageHero,
  SourceBadge,
  StatusPill,
} from "@/components/ui";
import { cn, compass, fixed, formatAge, formatShortUtc, formatUtc } from "@/lib/format";
import { useApi } from "@/lib/hooks";
import type { HistoryResponse, LatestResponse, Zone } from "@/lib/types";

const RANGES = [
  { minutes: 60, label: "1 hour" },
  { minutes: 360, label: "6 hours" },
  { minutes: 1440, label: "24 hours" },
];

export default function OceanPage() {
  const [zoneCode, setZoneCode] = useState("JKT-BAY");
  const [rangeMinutes, setRangeMinutes] = useState(360);
  const [anchor, setAnchor] = useState<number>(() => Date.now());

  useEffect(() => {
    const fromQuery = new URLSearchParams(window.location.search).get("zone");
    if (fromQuery) setZoneCode(fromQuery.toUpperCase());
  }, []);

  const zones = useApi<Zone[]>("/coastal/zones");
  const latest = useApi<LatestResponse>("/buoy/latest", 20000);

  const since = useMemo(() => new Date(anchor - rangeMinutes * 60_000).toISOString(), [anchor, rangeMinutes]);
  const history = useApi<HistoryResponse>(
    `/buoy/history?zone_code=${encodeURIComponent(zoneCode)}&page_size=500&observed_from=${encodeURIComponent(since)}`,
    30000,
  );

  const zone = zones.data?.find((item) => item.zone_code === zoneCode) ?? zones.data?.[0] ?? null;
  const observation =
    latest.data?.items.find((item) => item.zone_code === zoneCode) ??
    history.data?.items[0] ??
    null;
  const parameters = observation?.parameters;

  const quality = useMemo(() => {
    const items = history.data?.items ?? [];
    const valid = items.filter((item) => item.validation_status === "valid");
    const invalid = items.length - valid.length;
    const times = valid
      .map((item) => new Date(item.observed_at).getTime())
      .sort((a, b) => a - b);
    const gaps = times.slice(1).map((time, index) => (time - times[index]) / 60000);
    const medianGap = gaps.length
      ? [...gaps].sort((a, b) => a - b)[Math.floor(gaps.length / 2)]
      : null;
    return { count: valid.length, invalid, medianGap };
  }, [history.data]);

  const refreshAll = () => {
    setAnchor(Date.now());
    latest.refresh();
    history.refresh();
  };

  const selectZone = (code: string) => {
    setZoneCode(code);
    const url = new URL(window.location.href);
    url.searchParams.set("zone", code);
    window.history.replaceState({}, "", url);
  };

  return (
    <>
      <PageHero
        eyebrow="Ocean monitoring"
        title={
          <>
            Every reading,{" "}
            <span className="text-signal">with its receipt.</span>
          </>
        }
        description="Buoy telemetry, its physical units, its timestamps and its provenance. Simulated readings are generated by the CEWS buoy simulator and validated before they reach this view."
        right={
          <div className="flex flex-col items-start gap-2 lg:items-end">
            <SourceBadge kind="simulated" />
            <StatusPill tone={latest.data?.stale ? "warn" : "ok"}>
              {latest.data?.stale ? "Feed stale" : "Feed current"}
            </StatusPill>
            <button type="button" onClick={refreshAll} className="btn btn-ghost btn-sm">
              <RefreshCw className="h-3.5 w-3.5" aria-hidden /> Refresh
            </button>
          </div>
        }
      />

      <div className="space-y-6">
        {/* zone + range controls */}
        <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
          <div className="flex flex-wrap gap-2" role="tablist" aria-label="Coastal zone">
            {(zones.data ?? []).map((item) => (
              <button
                key={item.zone_code}
                type="button"
                role="tab"
                aria-selected={item.zone_code === zoneCode}
                onClick={() => selectZone(item.zone_code)}
                className={cn(
                  "rounded-full border px-4 py-2 text-[12px] font-bold transition",
                  item.zone_code === zoneCode
                    ? "border-ink bg-ink text-white"
                    : "border-line bg-white text-muted hover:border-line-strong hover:text-ink",
                )}
              >
                {item.zone_name}
                <span className={cn("ml-2 font-mono text-[9px]", item.zone_code === zoneCode ? "text-white/50" : "text-line-strong")}>
                  {item.zone_code}
                </span>
              </button>
            ))}
            {zones.loading && !zones.data ? <div className="skeleton h-9 w-40 rounded-full" /> : null}
          </div>

          <div className="flex items-center gap-2">
            <span className="text-[10px] font-extrabold uppercase tracking-[0.1em] text-muted">Window</span>
            <div className="flex rounded-full border border-line bg-white p-1">
              {RANGES.map((range) => (
                <button
                  key={range.minutes}
                  type="button"
                  onClick={() => setRangeMinutes(range.minutes)}
                  className={cn(
                    "rounded-full px-3 py-1.5 text-[11px] font-bold transition",
                    rangeMinutes === range.minutes ? "bg-ink text-white" : "text-muted hover:text-ink",
                  )}
                  aria-pressed={rangeMinutes === range.minutes}
                >
                  {range.label}
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* freshness strip */}
        <div className="card flex flex-col gap-4 p-5 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-wrap items-center gap-x-6 gap-y-2 text-[11.5px]">
            <span className="flex items-center gap-1.5 font-semibold text-ink">
              <span className="relative flex h-2 w-2">
                <span className="absolute inline-flex h-full w-full animate-ping rounded-full bg-signal opacity-60" />
                <span className="relative inline-flex h-2 w-2 rounded-full bg-signal" />
              </span>
              {zone?.zone_name ?? zoneCode}
            </span>
            <span className="text-muted">
              Last observation <strong className="font-semibold text-ink">{formatUtc(observation?.observed_at)}</strong>
            </span>
            <span className="text-muted">
              Received <strong className="font-semibold text-ink">{formatUtc(observation?.received_at)}</strong>
            </span>
            <span className="text-muted">
              Age <strong className="font-semibold text-ink">{formatAge(observation?.data_age_seconds)}</strong>
            </span>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="chip border-line-strong">Scenario · {observation?.scenario ?? "—"}</span>
            <span className="chip border-line-strong">v{observation?.generator_version ?? "—"}</span>
            {observation && observation.data_age_seconds > (latest.data?.stale_after_seconds ?? 300) ? (
              <StatusPill tone="warn">Stale &gt; {Math.round((latest.data?.stale_after_seconds ?? 300) / 60)} min</StatusPill>
            ) : (
              <StatusPill tone="ok">Within freshness window</StatusPill>
            )}
          </div>
        </div>

        {zone?.boundary_note ? (
          <p className="text-[10.5px] leading-relaxed text-muted">{zone.boundary_note}</p>
        ) : null}

        {/* metric grid */}
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          <MetricCard
            icon={Waves}
            label="Significant wave height"
            value={fixed(parameters?.wave_height_m, 2)}
            unit="m"
            hint="Simulated · last valid reading"
          />
          <MetricCard
            icon={Clock3}
            label="Dominant wave period"
            value={fixed(parameters?.wave_period_s, 1)}
            unit="s"
            hint="Coupled to wave height by the generator"
          />
          <MetricCard
            icon={Compass}
            label="Wave direction"
            value={parameters ? `${compass(parameters.wave_direction_deg)} ${fixed(parameters.wave_direction_deg, 0)}` : "—"}
            unit="°"
            hint="Direction the waves come from"
          />
          <MetricCard
            icon={Wind}
            label="Wind speed"
            value={fixed(parameters?.wind_speed_mps, 1)}
            unit="m/s"
            hint={parameters ? `From ${compass(parameters.wind_direction_deg)} ${fixed(parameters.wind_direction_deg, 0)}°` : "—"}
          />
          <MetricCard
            icon={Gauge}
            label="Air pressure"
            value={fixed(parameters?.air_pressure_hpa, 1)}
            unit="hPa"
            hint="Mean sea-level pressure"
          />
          <MetricCard
            icon={Thermometer}
            label="Sea-surface temperature"
            value={fixed(parameters?.sea_temperature_c, 1)}
            unit="°C"
            hint="Simulated at buoy depth"
          />
          <MetricCard
            icon={Droplets}
            label="Valid readings in window"
            value={String(quality.count)}
            unit="rows"
            hint={`${quality.invalid} invalid / quarantined excluded`}
          />
          <MetricCard
            icon={Clock3}
            label="Median sampling gap"
            value={quality.medianGap ? fixed(quality.medianGap, 0) : "—"}
            unit="min"
            hint="Computed from stored timestamps"
          />
        </div>

        {history.error ? (
          <div className="card border-signal/25 bg-signal-soft/50 p-5 text-[13px] text-signal-dark">
            {history.error}
          </div>
        ) : history.data ? (
          <ObservationCharts items={history.data.items} />
        ) : (
          <div className="grid gap-5 xl:grid-cols-[1.35fr_1fr]">
            <div className="skeleton h-[340px] rounded-[22px]" />
            <div className="skeleton h-[340px] rounded-[22px]" />
          </div>
        )}

        {/* table + provenance */}
        <div className="grid gap-5 xl:grid-cols-[1.6fr_1fr]">
          <div className="card overflow-hidden">
            <div className="flex flex-wrap items-center justify-between gap-3 border-b border-line px-5 py-4">
              <div>
                <h2 className="text-[15px] font-extrabold tracking-[-0.02em]">Recent readings</h2>
                <p className="mt-0.5 text-[11px] text-muted">
                  {history.data?.total ?? 0} row(s) in the selected window · newest first
                </p>
              </div>
              <SourceBadge kind="simulated" />
            </div>
            <div className="max-h-[430px] overflow-auto">
              <table className="w-full min-w-[580px] border-collapse text-left">
                <thead className="sticky top-0 z-10 bg-paper/95 backdrop-blur">
                  <tr className="text-[9.5px] font-extrabold uppercase tracking-[0.1em] text-muted">
                    <th className="px-5 py-2.5">Observed (UTC)</th>
                    <th className="px-3 py-2.5">H (m)</th>
                    <th className="px-3 py-2.5">T (s)</th>
                    <th className="px-3 py-2.5">Wind</th>
                    <th className="px-3 py-2.5">Pressure</th>
                    <th className="px-5 py-2.5">Status</th>
                  </tr>
                </thead>
                <tbody>
                  {(history.data?.items ?? []).slice(0, 14).map((item) => (
                    <tr key={item.id} className="table-row text-[12px]">
                      <td className="px-5 py-3 font-mono text-[11px] text-ink-soft">{formatShortUtc(item.observed_at)}</td>
                      <td className="metric px-3 py-3 font-semibold">{fixed(item.parameters.wave_height_m, 2)}</td>
                      <td className="metric px-3 py-3">{fixed(item.parameters.wave_period_s, 1)}</td>
                      <td className="metric px-3 py-3">{fixed(item.parameters.wind_speed_mps, 1)} m/s</td>
                      <td className="metric px-3 py-3">{fixed(item.parameters.air_pressure_hpa, 1)} hPa</td>
                      <td className="px-5 py-3">
                        <StatusPill tone={item.validation_status === "valid" ? "ok" : "bad"}>
                          {item.validation_status}
                        </StatusPill>
                      </td>
                    </tr>
                  ))}
                  {history.data && history.data.items.length === 0 ? (
                    <tr>
                      <td colSpan={6} className="px-5 py-10 text-center text-[12px] text-muted">
                        No readings in this window. Generate a scenario below.
                      </td>
                    </tr>
                  ) : null}
                </tbody>
              </table>
            </div>
          </div>

          <div className="card p-5">
            <h2 className="text-[15px] font-extrabold tracking-[-0.02em]">Reading provenance</h2>
            <p className="mt-1 text-[11px] leading-relaxed text-muted">
              Observed, received and processed times are stored separately so ingestion time is never
              confused with measurement time.
            </p>
            <dl className="mt-4 divide-y divide-line">
              <KeyValue label="Observation ID" value={<span className="font-mono text-[10px]">{observation?.id.slice(0, 8) ?? "—"}</span>} />
              <KeyValue label="Observed at" value={formatUtc(observation?.observed_at)} />
              <KeyValue label="Received at" value={formatUtc(observation?.received_at)} />
              <KeyValue label="Processed at" value={formatUtc(observation?.processed_at)} />
              <KeyValue label="Source type" value={observation?.source_type ?? "—"} />
              <KeyValue label="Simulation" value={<span className="font-mono text-[10px]">{observation?.simulation_id?.slice(0, 8) ?? "—"}</span>} />
              <KeyValue label="Validation" value={observation?.validation_status ?? "—"} />
              <KeyValue label="Buoy" value={observation?.buoy_code ?? "—"} />
              <KeyValue
                label="Position"
                value={
                  observation
                    ? `${fixed(observation.latitude, 3)}, ${fixed(observation.longitude, 3)}`
                    : "—"
                }
              />
            </dl>

            {observation?.validation_errors?.length ? (
              <div className="mt-4 rounded-xl border border-signal/20 bg-signal-soft/60 p-3 text-[11px] text-signal-dark">
                <p className="font-bold">Validation issues</p>
                <ul className="mt-1 list-inside list-disc space-y-1">
                  {observation.validation_errors.map((error) => (
                    <li key={error.code}>{error.message}</li>
                  ))}
                </ul>
              </div>
            ) : null}

            <div className="mt-4 rounded-xl bg-paper p-3 text-[10.5px] leading-relaxed text-muted">
              <strong className="text-ink">Unit note.</strong> Wave direction and wind direction are
              meteorological “coming from” angles in degrees true. Pressure is stored in hPa and never
              converted in the database.
            </div>
          </div>
        </div>

        {/* simulator */}
        <section id="simulator" className="scroll-mt-24 pt-4">
          <SimulatorPanel
            zones={zones.data ?? []}
            zoneCode={zoneCode}
            onZoneChange={selectZone}
            onCompleted={refreshAll}
          />
        </section>

        <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-line bg-white px-5 py-4">
          <p className="text-[11.5px] text-muted">
            Next step: screen this window with the anomaly model and the transparent risk rubric.
          </p>
          <Link href="/ai" className="btn btn-dark btn-sm">
            Open AI analysis <ArrowUpRight className="h-3.5 w-3.5" aria-hidden />
          </Link>
        </div>
      </div>
    </>
  );
}

function MetricCard({
  icon: Icon,
  label,
  value,
  unit,
  hint,
}: {
  icon: typeof Waves;
  label: string;
  value: string;
  unit: string;
  hint: string;
}) {
  return (
    <div className="card p-4">
      <div className="flex items-start justify-between gap-2">
        <p className="text-[9.5px] font-extrabold uppercase leading-snug tracking-[0.1em] text-muted">{label}</p>
        <span className="grid h-6 w-6 shrink-0 place-items-center rounded-full bg-paper text-sea">
          <Icon className="h-3 w-3" aria-hidden />
        </span>
      </div>
      <Metric label="" value={value} unit={unit} className="mt-2" />
      <p className="mt-1 text-[10px] leading-snug text-muted">{hint}</p>
    </div>
  );
}
