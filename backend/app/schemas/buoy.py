"""Buoy ingestion, history and simulator schemas."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field, field_validator

from app.schemas.common import ORMModel, ScenarioName, SourceType, UtcDatetime


class BuoyParameters(BaseModel):
    wave_height_m: float = Field(description="Significant wave height, metres")
    wave_period_s: float = Field(description="Dominant wave period, seconds")
    wave_direction_deg: float = Field(description="Wave coming-from direction, degrees true")
    wind_speed_mps: float = Field(description="Wind speed, metres per second")
    wind_direction_deg: float = Field(description="Wind coming-from direction, degrees true")
    sea_temperature_c: float = Field(description="Sea-surface temperature, degrees Celsius")
    air_pressure_hpa: float = Field(description="Mean sea-level pressure, hectopascal")


class BuoyObservationIn(BaseModel):
    simulation_id: uuid.UUID | None = None
    buoy_code: str = Field(min_length=2, max_length=32)
    observed_at: UtcDatetime
    latitude: float = Field(ge=-90, le=90)
    longitude: float = Field(ge=-180, le=180)
    parameters: BuoyParameters
    source_type: SourceType = "simulated"
    scenario: str = "normal"
    generator_version: str = "1.0.0"
    idempotency_key: str | None = Field(default=None, max_length=160)

    @field_validator("buoy_code")
    @classmethod
    def _normalise_code(cls, value: str) -> str:
        return value.strip().upper()

    @field_validator("scenario")
    @classmethod
    def _normalise_scenario(cls, value: str) -> str:
        allowed = {"normal", "warning", "extreme"}
        normalised = value.strip().lower()
        if normalised not in allowed:
            raise ValueError(f"scenario must be one of {sorted(allowed)}")
        return normalised


class BuoyDeviceOut(ORMModel):
    id: uuid.UUID
    buoy_code: str
    zone_id: uuid.UUID
    zone_code: str | None = None
    zone_name: str | None = None
    latitude: float | None = None
    longitude: float | None = None
    device_status: str
    source_type: str


class BuoyObservationOut(BaseModel):
    id: uuid.UUID
    buoy_code: str
    zone_code: str | None = None
    simulation_id: uuid.UUID | None = None
    observed_at: datetime
    received_at: datetime
    processed_at: datetime | None = None
    parameters: BuoyParameters
    latitude: float
    longitude: float
    source_type: str
    scenario: str
    generator_version: str
    validation_status: str
    validation_errors: list[dict] | None = None
    data_age_seconds: int
    idempotency_key: str


class BuoyIngestionResponse(BaseModel):
    accepted: bool
    duplicate: bool = False
    validation_status: str
    observation: BuoyObservationOut | None = None
    errors: list[dict] = []


class BuoyHistoryResponse(BaseModel):
    items: list[BuoyObservationOut]
    page: int
    page_size: int
    total: int
    has_next: bool


class BuoyLatestResponse(BaseModel):
    items: list[BuoyObservationOut]
    stale: bool
    stale_after_seconds: int


class ScenarioStartIn(BaseModel):
    zone_code: str = Field(default="JKT-BAY", max_length=32)
    buoy_code: str | None = Field(default=None, max_length=32)
    scenario: ScenarioName = "warning"
    mode: Literal["manual", "auto"] = "manual"
    interval_seconds: int = Field(default=60, ge=5, le=3600)
    observations: int = Field(
        default=12,
        ge=1,
        le=240,
        description="Number of synthetic observations generated by a manual scenario run.",
    )
    random_seed: int | None = Field(default=None, ge=0, le=2**31 - 1)
    notes: str | None = Field(default=None, max_length=500)


class SimulationJobOut(BaseModel):
    id: uuid.UUID
    scenario: str
    mode: str
    status: str
    zone_code: str | None = None
    random_seed: int
    generator_version: str
    interval_seconds: int
    observations_count: int
    started_at: datetime | None = None
    ended_at: datetime | None = None
    created_at: datetime
    notes: str | None = None


class SimulationJobCreated(BaseModel):
    job: SimulationJobOut
    acceptance_note: str
